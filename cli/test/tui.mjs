import assert from 'node:assert/strict';
import React from 'react';
import { EventEmitter } from 'node:events';
import { render } from 'ink-testing-library';
import { ConsoleModel, ShareConsole, terminalText } from '../dist/tui.js';
import { clientConfig } from '../dist/ui.js';
const delay = () => new Promise(resolve => setTimeout(resolve, 60));
const options = { version: '1.0.1', ticket: `wire://${'a'.repeat(64)}`, serverName: 'time"test', policyLine: '2 tools allowed (get_current_time, convert_time)', redact: true, confirm: true, ttlMs: 60000, maxCalls: 5, recordPath: null };
assert.equal(JSON.parse(clientConfig(options)).mcpServers['time"test'].args.at(-1), options.ticket);
assert.equal(terminalText('\x1b[2Jbad\x1b]52;c;YQ==\x07\rtext'), 'badtext');
const model = new ConsoleModel(options, { startedAt: Date.now(), peers: 0, calls: 0, blocked: 0, redactions: 0 });
const output = Object.assign(new EventEmitter(), { columns: 80, rows: 24 });
let quit = false;
const app = render(React.createElement(ShareConsole, { model, output, onQuit: () => { quit = true; } }));
try {
  await delay();
  assert.match(app.lastFrame(), /Connecting/);
  assert.match(app.lastFrame(), /mcpServers/);
  assert(app.lastFrame().split('\n').every(line => [...line].length <= 80));
  model.ready = true; model.log('Peer connected');
  app.stdin.write('2'); await delay();
  assert.match(app.lastFrame(), /Listening/);
  assert.match(app.lastFrame(), /Peer connected/);
  const answer = model.confirm('get_current_time', { timezone: 'UTC' });
  await delay();
  assert.match(app.lastFrame(), /Approval required/);
  app.stdin.write('y'); await delay();
  assert.equal(await answer, 'allow');
  const denied = model.confirm('another_tool', {});
  await delay(); app.stdin.write('n'); await delay();
  assert.equal(await denied, 'deny');
  const always = model.confirm('trusted_tool', {});
  await delay(); app.stdin.write('a'); await delay();
  assert.equal(await always, 'always');
  output.columns = 40; output.rows = 20; output.emit('resize'); await delay();
  assert(app.lastFrame().split('\n').every(line => [...line].length <= 40));
  app.stdin.write('1'); await delay();
  assert.match(app.lastFrame(), /mcpServers/);
  app.stdin.write('\x1b[B'); await delay();
  output.columns = 25; output.rows = 10; output.emit('resize'); await delay();
  assert.match(app.lastFrame(), /MCPWire/);
  app.stdin.write('q'); await delay(); assert(quit);
  const pending = model.confirm('pending', {});
  model.close(); assert.equal(await pending, 'deny');
  assert.equal(await model.confirm('closed', {}), 'deny');
  for (let i = 0; i < 300; i++) model.log(`event ${i}`);
  assert.equal(model.events.length, 200);
  console.log('TUI: layout, resize, navigation, approvals, sanitization, shutdown passed');
} finally { app.unmount(); app.cleanup(); }
